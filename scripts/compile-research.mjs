import {readFileSync,writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
const names=['culinary_substitution_sense.md','ingredient_prediction_rules.md'];
const documents=names.map(name=>{
 const content=readFileSync(new URL('../../Training/'+name,import.meta.url),'utf8');
 return {source:'Training/'+name,sha256:createHash('sha256').update(content).digest('hex'),status:'owner-supplied reference; individual numerical claims not independently verified',content};
});
const output=fileURLToPath(new URL('../src/lib/researchReferences.ts',import.meta.url));
writeFileSync(output,'// Generated by scripts/compile-research.mjs. Review rule changes before regenerating.\nexport const researchReferences = '+JSON.stringify(documents,null,2)+' as const;\n');
console.log('Compiled two source documents with SHA-256 provenance; no model-weight training performed.');
