import { unitLabel } from '../lib/displayText';
import React, { useState } from 'react';
import { X, FileText, Download, Copy, Check, Printer } from 'lucide-react';
import { OrderNote } from '../types';

interface ExportOrderModalProps {
  orderNote: OrderNote;
  onClose: () => void;
  currencySymbol: string;
}

export const ExportOrderModal: React.FC<ExportOrderModalProps> = ({
  orderNote,
  onClose,
  currencySymbol,
}) => {
  const [error, setError] = useState('');
  const [copied, setCopied] = useState(false);

  const poText = `PURCHASE ORDER: ${orderNote.po_number}
Supplier: ${orderNote.supplier_name}
Date: ${new Date(orderNote.created_at).toLocaleDateString()}

Items:
${orderNote.lines.map(l => `- ${l.ingredient_name}: ${l.order_qty} ${l.unit} @ ${currencySymbol}${l.unit_cost}/${l.unit} = ${currencySymbol}${l.subtotal.toFixed(2)}`).join('\n')}

TOTAL AMOUNT: ${currencySymbol}${orderNote.total_amount.toFixed(2)}
Generated by RestoBot`;

  const handleCopyText = async () => {
    setError('');
    try { await navigator.clipboard.writeText(poText); } catch { setError('Clipboard access failed. Download the CSV instead.'); return; }
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleDownloadCSV = () => {
    let csvStr = `PO Number,Supplier,Ingredient,Quantity,Unit,Unit Cost,Subtotal\n`;
    orderNote.lines.forEach(line => {
      csvStr += `"${orderNote.po_number}","${orderNote.supplier_name}","${line.ingredient_name}",${line.order_qty},"${line.unit}",${line.unit_cost},${line.subtotal}\n`;
    });

    const blob = new Blob([csvStr], { type: 'text/csv' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `${orderNote.po_number}_${orderNote.supplier_name.replace(/\s+/g, '_')}.csv`;
    a.click();
    URL.revokeObjectURL(url);
  };

  return (
    <div className="fixed inset-0 z-50 bg-slate-950/80 backdrop-blur-sm flex items-center justify-center p-4">
      <div className="bg-slate-900 border border-slate-800 rounded-2xl max-w-lg w-full p-6 shadow-2xl space-y-5 animate-fadeIn">
        
        {/* Header */}
        <div className="flex items-center justify-between pb-3 border-b border-slate-800">
          <div>
            <span className="text-[10px] font-extrabold uppercase text-teal-400 bg-teal-500/10 px-2 py-0.5 rounded border border-teal-500/30">
              {orderNote.po_number}
            </span>
            <h2 className="text-lg font-bold text-white mt-1">{orderNote.supplier_name}</h2>
          </div>
          <button onClick={onClose} className="text-slate-400 hover:text-white p-1">
            <X className="w-5 h-5" />
          </button>
        </div>

        {error && <p role="alert" className="text-rose-300">{error}</p>}
        {/* PO Items Table */}
        <div className="space-y-3">
          <div className="max-h-60 overflow-y-auto bg-slate-950/80 border border-slate-800 rounded-xl p-3 divide-y divide-slate-800 text-xs">
            {orderNote.lines.map((line, idx) => (
              <div key={idx} className="py-2 flex items-center justify-between">
                <div>
                  <div className="font-semibold text-slate-200">{line.ingredient_name}</div>
                  <div className="text-[10px] text-slate-500">{line.order_qty} {unitLabel(line.unit)} @ {currencySymbol}{line.unit_cost}</div>
                </div>
                <div className="font-bold text-teal-400 font-mono">
                  {currencySymbol}{line.subtotal.toFixed(2)}
                </div>
              </div>
            ))}
          </div>

          <div className="bg-slate-950 border border-slate-800 rounded-xl p-3.5 flex items-center justify-between text-sm">
            <span className="text-slate-400 font-medium">Total Purchase Amount:</span>
            <span className="text-xl font-extrabold text-amber-400 font-mono">
              {currencySymbol}{orderNote.total_amount.toFixed(2)}
            </span>
          </div>
        </div>

        {/* Export Actions */}
        <div className="flex flex-wrap items-center justify-end gap-2 pt-2">
          <button
            onClick={handleCopyText}
            className="bg-slate-800 hover:bg-slate-700 text-slate-200 text-xs font-semibold px-4 py-2.5 rounded-xl border border-slate-700 transition flex items-center space-x-2"
          >
            {copied ? <Check className="w-4 h-4 text-emerald-400" /> : <Copy className="w-4 h-4 text-slate-400" />}
            <span>{copied ? 'Copied to Clipboard!' : 'Copy Text (WhatsApp)'}</span>
          </button>

          <button
            onClick={handleDownloadCSV}
            className="bg-teal-600 hover:bg-teal-500 text-slate-950 font-bold text-xs px-5 py-2.5 rounded-xl shadow transition flex items-center space-x-2"
          >
            <Download className="w-4 h-4" />
            <span>Download CSV</span>
          </button>
        </div>

      </div>
    </div>
  );
};
